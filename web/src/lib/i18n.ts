import type { Locale, Market } from "./types";

export const DEFAULT_LOCALE: Record<Market, Locale> = { BR: "pt-BR", US: "en-US" };

export function formatMoney(minor: number, market: Market, locale: Locale): string {
  return new Intl.NumberFormat(locale, { style: "currency", currency: market === "BR" ? "BRL" : "USD" }).format(minor / 100);
}

export function formatDateTime(iso: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale, { dateStyle: "short", timeStyle: "short" }).format(new Date(iso));
}

